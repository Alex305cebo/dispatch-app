/** "70445" → "LA"; неизвестный или не индекс — null. */
export function zipState(zip: string | null | undefined): string | null {
  const m = /^(\d{3})\d{2}$/.exec((zip ?? '').trim())
  if (!m) return null
  const p = Number(m[1])
  for (const [from, to, st] of RANGES) if (p >= from && p <= to) return st
  return null
}
