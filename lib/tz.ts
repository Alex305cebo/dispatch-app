import tzLookup from 'tz-lookup'

/**
 * Часовой пояс по координатам — офлайн, без единого обращения наружу.
 *
 * Почему не по API. Google и подобные отдают это ключом и запросом на каждую
 * точку; для строки, которая обновляется на каждой загрузке страницы у каждого
 * трака, это лишний внешний сервис и лишний расход квоты. Пакет tz-lookup
 * держит полигоны поясов в себе (150 КБ) и отвечает мгновенно.
 *
 * Почему не «по долготе» руками. Соблазн велик — США же вытянуты по широте, —
 * но границы поясов идут не по меридианам: панхандл Айдахо тихоокеанский, а
 * северо-запад Индианы центральный, хотя оба «не по долготе». Неверное время у
 * водителя хуже, чем его отсутствие: по нему звонят и назначают окна.
 */
export function zoneFor(lat: number | null | undefined, lng: number | null | undefined): string | null {
  if (typeof lat !== 'number' || typeof lng !== 'number') return null
  if (!Number.isFinite(lat) || !Number.isFinite(lng)) return null
  try {
    return tzLookup(lat, lng)
  } catch {
    // Координаты вне суши (океан) — библиотека бросает. Это не повод ронять страницу.
    return null
  }
}
