// <Suspense> для серверных страниц. Ставить ЭТОТ, а не Suspense из 'react'.
//
// Отличие одно — fallback уходит в React массивом. С голым Suspense граница, досылаемая
// потоком, может так и не завершиться: в HTML остаётся метка <!--$?-->, которой не приходит
// $RC, и браузер бросает React #419 и перерисовывает страницу с нуля. Обзор так падал на
// каждой загрузке при английском языке.
//
// Откуда. RSC-сервер выносит в отдельную строку потока любой элемент, до которого дошёл,
// когда текущая строка перевалила за 3200 байт; при SSR такой элемент приходит позже.
// Если это сам fallback, React (19.2 — и внутри Next 15.5, и стабильный 19.2.7) ставит на
// место fallback заглушку, а дождавшись его, выводит границу ЕЩЁ РАЗ под новым номером:
// содержимое досылается уже туда, а первая метка ждёт вечно. На какой элемент придётся
// 3200-й байт, решает длина текста выше: при ru вынесло детей fallback, и всё работало,
// при en — его самого.
//
// Массив React выводит сразу, а ждёт уже его элемент, отдельным куском, — граница
// выводится один раз. Children.toArray, а не [fallback]: ключ ставит сам.
// Без JSX — чтобы lib/suspense.test.ts мог импортировать файл под node --test.

import { Children, createElement, Suspense as ReactSuspense, type ReactNode } from 'react'

export function Suspense({ fallback, children }: { fallback?: ReactNode; children?: ReactNode }) {
  return createElement(ReactSuspense, { fallback: Children.toArray(fallback) }, children)
}
